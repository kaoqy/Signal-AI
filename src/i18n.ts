export function setLanguage(language: Language): void {
  currentLanguage = language;
  try { localStorage.setItem('monitor-language', language); } catch { /* language preference is optional */ }
}

export function tr(text: string): string {
  if (currentLanguage !== 'zh-CN') return text;
  const trimmed = text.replace(/\s+/g, ' ').trim();
  if (!trimmed) return text;
  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  const statMatchers: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^(\d+) disabled$/, ([, count]) => `${count} 个已停用`],
    [/^([\d.]+)% uptime in 24h$/, ([, percent]) => `过去 24 小时可用率 ${percent}%`],
    [/^(\d+) checks in 24h$/, ([, count]) => `过去 24 小时检测 ${count} 次`],
    [/^(\d+) resolved$/, ([, count]) => `已解决 ${count} 起`],
    [/^Median (.+)$/, ([, value]) => `中位数 ${value}`],
    [/^Max (.+)$/, ([, value]) => `最大值 ${value}`],
    [/^TTFT (.+)$/, ([, value]) => `首 Token ${value}`],
  ];
  let translated = translations[trimmed];
  if (!translated) {
    for (const [pattern, format] of statMatchers) {
      const match = trimmed.match(pattern);
      if (match) { translated = format(match); break; }
    }
  }
  return translated ? `${leading}${translated}${trailing}` : text;
}

